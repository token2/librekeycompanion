import org.junit.Test

/**
 * Key types named from a certificate's subjectPublicKeyInfo. The certificates
 * are throwaway ones made with OpenSSL 3.5 for this test (`openssl req -x509
 * -newkey ...`; the X25519 one signed by the Ed25519 one, since X25519 can't
